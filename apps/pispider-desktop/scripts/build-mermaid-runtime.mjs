import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
let sourcePackage;
try {
  sourcePackage = require.resolve("mermaid/package.json");
} catch (error) {
  throw new Error(`Mermaid is not installed: ${error.message}`);
}
const sourceDist = path.join(path.dirname(sourcePackage), "dist");
const vendorDir = path.join(appDir, "vendor", "mermaid");
const tempDir = path.join(appDir, "vendor", `.mermaid-build-${process.pid}`);

if (!fs.existsSync(sourceDist) || !fs.existsSync(sourcePackage)) {
  throw new Error("Mermaid is not installed");
}

const entryFile = path.join(sourceDist, "mermaid.esm.min.mjs");
const entryText = fs.readFileSync(entryFile, "utf8");
const version = JSON.parse(fs.readFileSync(sourcePackage, "utf8")).version;
const diagramRoots = [
  ...new Set(
    [...entryText.matchAll(/import\("\.\/chunks\/mermaid\.esm\.min\/((?:flowDiagram|sequenceDiagram)-[A-Z0-9]+\.mjs)"\)/g)].map(
      (match) => path.join(sourceDist, "chunks", "mermaid.esm.min", match[1]),
    ),
  ),
];
if (diagramRoots.length !== 2) {
  throw new Error(`Expected flowchart and sequence diagram chunks, found ${diagramRoots.length}`);
}

const optionalPrefixes = ["elk-", "dagre-", "swimlanes-", "cose-bilkent-", "katex-", "bpmnIcons-"];
const optionalRoots = optionalPrefixes.flatMap((prefix) =>
  fs
    .readdirSync(path.join(sourceDist, "chunks", "mermaid.esm.min"))
    .filter((name) => name.startsWith(prefix) && name.endsWith(".mjs"))
    .map((name) => path.join(sourceDist, "chunks", "mermaid.esm.min", name)),
);

const files = new Set();
const queue = [entryFile, ...diagramRoots, ...optionalRoots];
while (queue.length > 0) {
  const file = queue.shift();
  if (!file || files.has(file)) continue;
  if (!fs.existsSync(file)) throw new Error(`Missing Mermaid runtime file: ${file}`);
  files.add(file);
  const text = fs.readFileSync(file, "utf8");
  for (const match of text.matchAll(/from\s*["']([^"']+)["']/g)) {
    if (!match[1].startsWith(".")) continue;
    queue.push(path.resolve(path.dirname(file), match[1]));
  }
}

const records = [...files]
  .sort()
  .map((file) => ({
    path: path.relative(sourceDist, file).replaceAll("\\", "/"),
    bytes: fs.statSync(file).size,
  }));

const targetManifest = path.join(vendorDir, "manifest.json");
if (fs.existsSync(vendorDir) && !fs.existsSync(targetManifest)) {
  throw new Error("Refusing to replace vendor/mermaid because it was not generated by this script");
}

fs.rmSync(tempDir, { recursive: true, force: true });
fs.mkdirSync(tempDir, { recursive: true });
for (const record of records) {
  const target = path.join(tempDir, record.path);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.copyFileSync(path.join(sourceDist, record.path), target);
}
fs.writeFileSync(
  path.join(tempDir, "manifest.json"),
  `${JSON.stringify(
    {
      package: "mermaid",
      version,
      entry: "mermaid.esm.min.mjs",
      diagrams: ["flowchart", "sequence"],
      files: records,
      bytes: records.reduce((sum, record) => sum + record.bytes, 0),
    },
    null,
    2,
  )}\n`,
  "utf8",
);

fs.rmSync(vendorDir, { recursive: true, force: true });
fs.renameSync(tempDir, vendorDir);
console.log(
  `Mermaid ${version} runtime: ${records.length} files, ${(records.reduce((sum, record) => sum + record.bytes, 0) / 1024 / 1024).toFixed(2)} MB`,
);
